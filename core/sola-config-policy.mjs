const allowed = new Set(preferenceKeys);
const forbidden = k => /^(?:__proto__|constructor|prototype)$/i.test(k) || /(?:^|_)(?:api_?key|apikey|password|secret|access_token|auth_token|bearer_token|refresh_token|authorization|credentials)(?:$|_)/i.test(k);
function clean(v,depth=0){
  if(depth>25)throw new Error('Config nesting limit');
  if(Array.isArray(v))return v.map(x=>clean(x,depth+1));
  if(v&&typeof v==='object')return Object.fromEntries(Object.entries(v).filter(([k])=>!forbidden(k)&&(depth!==0||allowed.has(k))).sort(([a],[b])=>a.localeCompare(b)).map(([k,x])=>[k,clean(x,depth+1)]));
  return v;
}
export function sanitize(v){if(!v||typeof v!=='object'||Array.isArray(v))throw new Error('Invalid settings object');return clean(v);}
const text=v=>typeof v==='string'&&v.trim().length>0;
function url(v){try{const u=new URL(v);return ['http:','https:'].includes(u.protocol)&&!u.username&&!u.password;}catch{return false;}}
export function validate(v,previous=null){
  if(!v||Object.keys(v).length<50||(previous&&Object.keys(v).length<Math.ceil(Object.keys(previous).length*.75)))return false;
  if(!text(v.chat_provider)||!text(v.chat_model)||!text(v.embedding_provider)||!text(v.vector_backend))return false;
  if(['vllm','custom'].includes(v.chat_provider)&&!url(v.chat_vllm_url))return false;
  if(v.embedding_provider==='vllm'&&(!text(v.embedding_vllm_model)||(v.embedding_vllm_url_override&&!url(v.embedding_vllm_url))))return false;
  if(v.vector_backend==='qdrant'&&v.qdrant_use_cloud&&!url(v.qdrant_url))return false;
  return true;
}
